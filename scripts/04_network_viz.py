"""
Network visualizations — replaces VOSviewer with Python-native tooling.

Builds three views from the co-occurrence CSVs already generated by
02_bibliometric_analysis.py:

    1. Keyword co-occurrence network (polycrisis + LtG separately)
    2. Author co-authorship network (top authors by paper count)
    3. Polycrisis <-> LtG convergence map (shared keywords between corpora)

Outputs:
    figures/net_<name>.html   interactive (pyvis)
    figures/net_<name>.png    static (matplotlib), publication-ready
"""

from __future__ import annotations

import re
from collections import Counter
from itertools import combinations
from pathlib import Path

import matplotlib.pyplot as plt
import networkx as nx
import pandas as pd
from pyvis.network import Network

ROOT = Path(__file__).parent.parent
DATA = ROOT / "data"
FIGS = ROOT / "figures"
FIGS.mkdir(exist_ok=True)

# Generic OpenAlex concept tags that add noise, not signal.
STOPWORDS = {
    "computer science", "mathematics", "physics", "psychology",
    "engineering", "biology", "chemistry", "art", "humanities",
    "content (measure theory)", "action (physics)",
    "quantum entanglement",
}


def _louvain(G: nx.Graph) -> dict[str, int]:
    """Community detection — Louvain if available, else greedy modularity."""
    try:
        communities = nx.community.louvain_communities(G, seed=42)
    except Exception:
        communities = list(nx.community.greedy_modularity_communities(G))
    return {n: i for i, comm in enumerate(communities) for n in comm}


def build_cooc_graph(cooc_csv: Path, top_n: int = 60, min_weight: int = 5) -> nx.Graph:
    df = pd.read_csv(cooc_csv)
    df = df[~df["term1"].isin(STOPWORDS) & ~df["term2"].isin(STOPWORDS)]
    df = df[df["cooccurrence"] >= min_weight]

    # Restrict to top_n most connected terms
    freq = Counter()
    for _, r in df.iterrows():
        freq[r["term1"]] += r["cooccurrence"]
        freq[r["term2"]] += r["cooccurrence"]
    keep = {t for t, _ in freq.most_common(top_n)}
    df = df[df["term1"].isin(keep) & df["term2"].isin(keep)]

    G = nx.Graph()
    for _, r in df.iterrows():
        G.add_edge(r["term1"], r["term2"], weight=int(r["cooccurrence"]))
    for n in G.nodes():
        G.nodes[n]["size"] = freq[n]
    return G


def build_coauthor_graph(papers_csv: Path, top_n: int = 80, min_papers: int = 2) -> nx.Graph:
    df = pd.read_csv(papers_csv)
    df = df.dropna(subset=["authors"])

    author_counts: Counter[str] = Counter()
    paper_authors: list[list[str]] = []
    for auth_str in df["authors"]:
        # Strip "et al." suffix and split
        clean = re.sub(r"\s*\(\+\d+\)", "", str(auth_str))
        authors = [a.strip() for a in clean.split(";") if a.strip() and "et al." not in a]
        paper_authors.append(authors)
        for a in authors:
            author_counts[a] += 1

    keep = {a for a, c in author_counts.items() if c >= min_papers}
    keep = set(sorted(keep, key=lambda a: -author_counts[a])[:top_n])

    G = nx.Graph()
    for authors in paper_authors:
        filtered = [a for a in authors if a in keep]
        for a, b in combinations(filtered, 2):
            if G.has_edge(a, b):
                G[a][b]["weight"] += 1
            else:
                G.add_edge(a, b, weight=1)
    for n in list(G.nodes()):
        G.nodes[n]["size"] = author_counts[n]
    # Drop isolates
    G.remove_nodes_from(list(nx.isolates(G)))
    return G


def build_convergence_graph(poly_freq: Path, ltg_freq: Path, top_n: int = 40) -> nx.Graph:
    """Bipartite-ish view: shared keywords between the two corpora."""
    poly = pd.read_csv(poly_freq).head(top_n).set_index("term")["count"]
    ltg = pd.read_csv(ltg_freq).head(top_n).set_index("term")["count"]
    shared = set(poly.index) & set(ltg.index) - STOPWORDS

    G = nx.Graph()
    G.add_node("POLYCRISIS", kind="corpus", size=1000)
    G.add_node("LIMITS TO GROWTH", kind="corpus", size=1000)
    for term in shared:
        G.add_node(term, kind="keyword", size=int(poly[term] + ltg[term]))
        G.add_edge("POLYCRISIS", term, weight=int(poly[term]))
        G.add_edge("LIMITS TO GROWTH", term, weight=int(ltg[term]))
    return G


def render_pyvis(G: nx.Graph, out: Path, title: str) -> None:
    communities = _louvain(G) if len(G) > 2 else {n: 0 for n in G.nodes()}
    # Precompute a stable layout in networkx, then freeze physics in pyvis.
    pos = nx.spring_layout(G, seed=42, k=1.2, iterations=200)
    net = Network(height="850px", width="100%", bgcolor="#1a1a1a",
                  font_color="#ffffff", notebook=False, cdn_resources="remote")
    max_size = max((G.nodes[n].get("size", 1) for n in G.nodes()), default=1)
    scale = 900  # pixel spread
    for n in G.nodes():
        size = G.nodes[n].get("size", 1)
        scaled = 12 + 45 * (size / max_size)
        x, y = pos[n]
        net.add_node(n, label=n, value=float(size), size=scaled,
                     group=communities.get(n, 0),
                     x=float(x) * scale, y=float(y) * scale,
                     physics=False, fixed=False,
                     title=f"{n}<br>weight: {size}")
    for u, v, d in G.edges(data=True):
        net.add_edge(u, v, value=d.get("weight", 1), physics=False)
    net.set_options("""{
      "physics": {"enabled": false},
      "interaction": {"hover": true, "tooltipDelay": 100, "dragNodes": true, "zoomView": true},
      "nodes": {"font": {"size": 18, "face": "Helvetica", "color": "#ffffff", "strokeWidth": 3, "strokeColor": "#000000"}, "borderWidth": 1, "shape": "dot"},
      "edges": {"color": {"color": "#666", "opacity": 0.35}, "smooth": false}
    }""")
    net.write_html(str(out), notebook=False, open_browser=False)
    print(f"  interactive -> {out.relative_to(ROOT)}")


def render_static(G: nx.Graph, out: Path, title: str) -> None:
    if len(G) == 0:
        print(f"  (skip static — empty graph: {title})")
        return
    communities = _louvain(G) if len(G) > 2 else {n: 0 for n in G.nodes()}
    pos = nx.spring_layout(G, seed=42, k=0.8, iterations=100)
    max_size = max((G.nodes[n].get("size", 1) for n in G.nodes()), default=1)
    sizes = [80 + 1500 * (G.nodes[n].get("size", 1) / max_size) for n in G.nodes()]
    colors = [communities.get(n, 0) for n in G.nodes()]
    weights = [G[u][v].get("weight", 1) for u, v in G.edges()]
    max_w = max(weights) if weights else 1

    fig, ax = plt.subplots(figsize=(14, 10))
    nx.draw_networkx_edges(G, pos, alpha=0.25,
                           width=[0.3 + 3 * (w / max_w) for w in weights], ax=ax)
    nx.draw_networkx_nodes(G, pos, node_size=sizes, node_color=colors,
                           cmap="tab20", alpha=0.9, ax=ax)
    nx.draw_networkx_labels(G, pos, font_size=8, ax=ax)
    ax.set_title(title, fontsize=14)
    ax.axis("off")
    fig.tight_layout()
    fig.savefig(out, dpi=200, bbox_inches="tight")
    plt.close(fig)
    print(f"  static      -> {out.relative_to(ROOT)}")


def run(name: str, G: nx.Graph, title: str) -> None:
    print(f"[{name}] nodes={len(G)} edges={G.number_of_edges()}")
    render_pyvis(G, FIGS / f"net_{name}.html", title)
    render_static(G, FIGS / f"net_{name}.png", title)


def main() -> None:
    run("polycrisis_keywords",
        build_cooc_graph(DATA / "polycrisis_keyword_cooccurrence.csv"),
        "Polycrisis — keyword co-occurrence")

    run("ltg_keywords",
        build_cooc_graph(DATA / "ltg_keyword_cooccurrence.csv"),
        "Limits to Growth — keyword co-occurrence")

    run("polycrisis_coauthors",
        build_coauthor_graph(DATA / "polycrisis_papers.csv"),
        "Polycrisis — co-authorship")

    ltg_papers = DATA / "ltg_refined_papers.csv"
    if not ltg_papers.exists():
        ltg_papers = DATA / "ltg_papers.csv"
    run("ltg_coauthors",
        build_coauthor_graph(ltg_papers),
        "Limits to Growth — co-authorship")

    run("convergence",
        build_convergence_graph(
            DATA / "polycrisis_keyword_cooccurrence_frequencies.csv",
            DATA / "ltg_keyword_cooccurrence_frequencies.csv",
        ),
        "Polycrisis <-> Limits to Growth — shared keywords")

    print("\nDone. Open the .html files in a browser for interactive maps.")


if __name__ == "__main__":
    main()
